package locales

import "strings"

// ComparisonContext строит блок-инструкцию для ИИ при ПОВТОРНОМ анализе или
// биоскане: подсказывает, что у пользователя УЖЕ ЕСТЬ предыдущий отчёт, и
// просит построить СРАВНИТЕЛЬНЫЙ отчёт (что улучшилось, что улучшить),
// а не «с нуля». prevJSON - «чистый» JSON предыдущего отчёта (из истории).
//
// kind принимает значения "analysis" или "bioscan" - они лишь слегка меняют
// формулировку в тексте. Возвращает пустую строку, если prevJSON пуст.
func ComparisonContext(prevJSON string, kind string) string {
	prevJSON = trimJSON(prevJSON)
	if prevJSON == "" {
		return ""
	}

	subject := "расширенный анализ"
	if kind == "bioscan" {
		subject = "Bioscan PRO"
	}

	return "\n\n" +
		"══════════════════════════════════════════════\n" +
		"ВАЖНО: это ПОВТОРНЫЙ " + subject + " пользователя. У него УЖЕ ЕСТЬ предыдущий отчёт, " +
		"и он хочет видеть ДИНАМИКУ (прогресс), а не просто новый отчёт «с нуля».\n" +
		"Ниже - JSON ПРЕДЫДУЩЕГО отчёта (используй ТОЛЬКО для сравнения, не выдумывай в нём новые данные " +
		"и не смешивай его значения с текущими):\n" +
		"--- ПРЕДЫДУЩИЙ ОТЧЁТ (только для сравнения) ---\n" +
		prevJSON + "\n" +
		"--- КОНЕЦ ПРЕДЫДУЩЕГО ОТЧЁТА ---\n\n" +
		"Сформируй СРАВНИТЕЛЬНЫЙ отчёт. В JSON добавь верхнеуровневое поле \"comparison\" со структурой:\n" +
		"{\n" +
		"  \"improved\": [\"что улучшилось по сравнению с предыдущим отчётом (с цифрами: «гемоглобин 145→152»)\"],\n" +
		"  \"unchanged\": [\"что осталось без изменений\"],\n" +
		"  \"worsened\": [\"что ухудшилось или требует внимания (с цифрами)\"],\n" +
		"  \"to_improve\": [\"конкретные рекомендации, на чём сосредоточиться в следующий период\"],\n" +
		"  \"metrics\": [\n" +
		"    {\"name\":\"название показателя\",\"before\":\"значение в ПРЕДЫДУЩЕМ отчёте\",\"after\":\"значение в ТЕКУЩЕМ отчёте\",\"change\":\"краткая дельта, напр. +7 или -1.2\",\"trend\":\"up|down|same\"}\n" +
		"  ],\n" +
		"  \"summary\": \"2-3 предложения: общая динамика между отчётами, что стало лучше и что подтянуть\"\n" +
		"}\n" +
		"Требования к сравнению:\n" +
		"- В improved/worsened ОБЯЗАТЕЛЬНО указывай цифры до→после (например, «глюкоза 6.8→5.6»), а не просто «нормализовалась».\n" +
		"- В metrics перечисли 3-6 ключевых показателей, по которым есть данные в ОБОИХ отчётах, с реальными before/after и трендом.\n" +
		"- В to_improve дай 2-4 конкретных, выполнимых шага (питание/тренировки/режим), на чём сфокусироваться.\n" +
		"- Не выдумывай данные: если показателя нет в одном из отчётов - не включай его в metrics и не придумывай цифры.\n" +
		"══════════════════════════════════════════════\n"
}

// trimJSON убирает обёртку ```json ... ``` и лишние пробелы.
func trimJSON(s string) string {
	out := s
	for {
		trimmed := trimOneJSONFence(out)
		if trimmed == out {
			break
		}
		out = trimmed
	}
	return out
}

func trimOneJSONFence(s string) string {
	out := strings.TrimPrefix(s, "```json")
	out = strings.TrimPrefix(out, "```")
	out = strings.TrimSuffix(out, "```")
	return strings.TrimSpace(out)
}
