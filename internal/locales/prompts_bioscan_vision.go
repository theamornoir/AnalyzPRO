// PromptForBioscanBasicVision - промпт для БАЗОВОГО (бесплатного) Bioscan с
// мультимодальным (vision) анализом фото. В отличие от PromptForBioscanBasic,
// здесь модель РЕАЛЬНО ВИДИТ приложенное фото (оно передаётся в
