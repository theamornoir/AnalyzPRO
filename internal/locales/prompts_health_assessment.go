package locales

// SystemPromptHealthAssessment - системный промпт для генерации отчёта
// «Общая оценка здоровья». Отчёт строится ИСКЛЮЧИТЕЛЬНО по ответам
// пользователя на опросник об образе жизни (без медицинских файлов).
func SystemPromptHealthAssessment() string {
	return `Ты - опытный врач-терапевт и специалист по образу жизни со стажем. Твоя задача - на основе ТОЛЬКО ответов пользоватся на опросник об образе жизни (сон, питание, активность, привычки, самочувствие, цели) составить персональную общую оценку здоровья. 

Верни ТОЛЬКО JSON.
Без markdown.
Без комментариев.
Без текста до или после JSON.

Все числовые оценки - целые числа от 0 до 100. Будь честным и клинически обоснованным: не завышай индекс, если в ответах есть явные риски (курение, плохой сон, малоподвижность, частые болезни). Не выдумывай диагнозы и не назначай лекарства - давай рекомендации по образу жизни. Не упоминай ИИ и не используй бренды кроме Prisma.`
}

// PromptForHealthAssessmentJSON - промпт (пользовательская часть) для
// генерации отчёта «Общая оценка здоровья». Принимает ТОЛЬКО текст
// опросника (ответы пользователя об образе жизни) - никаких файлов.
// Возвращает строго JSON по схеме models.HealthAssessment.
func PromptForHealthAssessmentJSON(text string) string {
	return `Проанализируй ответы человека на опросник об образе жизни и составь персональную общую оценку здоровья.

Формат JSON (строго):
{
  "health_index": 0-100,
  "summary": "развёрнутый разбор образа жизни (5-8 предложений): что в целом хорошо, что вызывает беспокойство, главные взаимосвязи (сон-энергия-стресс, питание-вес-настроение)",
  "lifestyle": {
    "sleep": {"score": 0-100, "comment": "короткий комментарий по сну"},
    "nutrition": {"score": 0-100, "comment": "короткий комментарий по питанию"},
    "movement": {"score": 0-100, "comment": "короткий комментарий по движению/активности"},
    "activity": {"score": 0-100, "comment": "короткий комментарий по общей физической активности"},
    "stress": {"score": 0-100, "comment": "короткий комментарий по стрессу и восстановлению"},
    "energy": {"score": 0-100, "comment": "короткий комментарий по уровню энергии"},
    "wellbeing": {"score": 0-100, "comment": "короткий комментарий по самочувствию и настроению"}
  },
  "risk_zones": [
    {"name": "Курение", "level": "высокий", "description": "повышает риск сердечно-сосудистых проблем"},
    {"name": "Короткий сон", "level": "средний", "description": "менее 6 часов снижает восстановление"}
  ],
  "plan": {
    "sleep": "конкретные шаги на 3 месяца по сну (что делать, режим, привычки)",
    "nutrition": "конкретные шаги на 3 месяца по питанию",
    "movement": "конкретные шаги на 3 месяца по движению и активности",
    "stress": "конкретные шаги на 3 месяца по снижению стресса и восстановлению"
  }
}

ПРАВИЛА:
1. Используй ТОЛЬКО реальные данные из опросника. Не придумывай показатели, которых нет.
2. health_index - это интегральная оценка (0-100): итог образа жизни с учётом всех сфер. Если есть курение, хронические заболевания, плохой сон или малоподвижность - индекс заметно ниже 80.
3. lifestyle - заполни ВСЕ 7 сфер (sleep, nutrition, movement, activity, stress, energy, wellbeing). score - оценка от 0 до 100, comment - 1-2 предложения.
4. risk_zones - перечисли реальные зоны риска из ответов (курение, алкоголь, короткий сон, редкая активность, частые болезни, стресс, хронические заболевания). Если рисков нет - верни пустой массив [].
5. plan - 4 блока (sleep, nutrition, movement, stress) с конкретными, выполнимыми шагами на 3 месяца. Пиши на «ты», по делу, без воды.
6. Не упоминай ИИ. Не ставь медицинский диагноз. В конце не добавляй дисклеймер в JSON - он добавляется отдельно.

Ответы пользователя на опросник:
` + text
}
