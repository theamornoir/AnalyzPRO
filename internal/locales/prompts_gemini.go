// PromptForAnalysisFile - пользовательский промпт анализа одного файла.
// text содержит служебный контекст документа и данные пациента.
// Формат вывода - структурированный текст для Telegram (эмодзи-маркеры
// ✅/❌/●/✦ по шаблону пользователя, без markdown-разметки и звёздочек).
func PromptForAnalysisFile(text string) string {
	return `Внимательно проанализируй приложенный медицинский документ целиком (все страницы, таблицы, мелкий текст, подписи) и оформи разбор в строгом формате для Telegram.

ФОРМАТ ВЫВОДА:
1. Первая строка - заголовок: 🔬 АНАЛИЗ КРОВИ · [дата исследования из бланка]
2. Группируй показатели по разделам (ОАК, Биохимия, Липиды, Гормоны, Моча и т.п.). Каждый раздел начинай с маркера: ● [НАЗВАНИЕ РАЗДЕЛА]
3. Для каждого показателя - блок из трёх строк:
   ✅/❌ [Название показателя]
   [значение] [единица] ([референс])
   [1-2 предложения: что показывает этот показатель и что значит отклонение]
   (ставь ✅ если значение внутри референса, ❌ если выше или ниже)
4. Особо важный раздел (с отклонениями) можно пометить: ● ЛИПИДЫ (главное внимание)
5. В конце два блока:
   ● ВЫВОДЫ
   [2-3 предложения об общей картине и главных рисках; выдели критические отклонения]
   ● РЕКОМЕНДАЦИИ
   ✦ [конкретная рекомендация 1]
   ✦ [конкретная рекомендация 2]
   ✦ [рекомендация 3-5]
6. Последняя строка: Разбор информационный, не заменяет консультацию врача

ПРАВИЛА:
- Выписывай ВСЕ измеренные показатели из документа, ничего не пропуская.
- Референс бери из самого бланка; если не указан - по общепринятым клиническим нормам.
- Не придумывай показатели, которых нет в документе, и не искажай значения.
- Пиши на русском, по делу, без запугивания. Без markdown-разметки и звёздочек для жирности. Между блоками - пустая строка.

` + text
}

