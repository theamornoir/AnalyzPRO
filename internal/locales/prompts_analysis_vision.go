package locales

// PromptForAnalysisVision - промпт для консультации по ПРИЛОЖЕННОМУ ФОТО
// (травма/проблемная зона и т.п.) через мультимодальный (vision) запрос.
// В отличие от PromptForAnalysisFile, здесь модель РЕАЛЬНО ВИДИТ фото
// (оно передаётся в messages[].images) и анализирует его напрямую, а не
// через OCR (который с «живого» фото тела/травмы извлекает ~0 символов).
// contextText - дополнительный контекст (вопрос пользователя к фото и т.п.).
func PromptForAnalysisVision(contextText string) string {
	return `К этому сообщению ПРИЛОЖЕНО ФОТО (травма, проблемная зона, высыпание, снимок и т.п.). Ты его ВИДИШЬ и анализируешь напрямую - это главный источник данных. Внимательно разбери приложенное фото и оформи консультацию в строгом формате для Telegram.

ФОРМАТ ВЫВОДА:
1. Первая строка - заголовок: 🩺 КОНСУЛЬТАЦИЯ ПО ФОТО
2. Блок визуальной оценки:
   ● ЧТО ВИДНО НА ФОТО
   [2-4 предложения: что именно изображено, локализация, выраженность, цвет/отёк/форма, любые детали, важные для оценки]
3. Блок возможных причин:
   ● ВОЗМОЖНЫЕ ПРИЧИНЫ
   ✦ [причина 1 - кратко, обоснованно увиденным]
   ✦ [причина 2]
   ✦ [причина 3 при наличии]
4. Блок рекомендаций:
   ● ЧТО ДЕЛАТЬ
   ✦ [практическая рекомендация 1 - облегчение состояния, уход, первая помощь]
   ✦ [рекомендация 2]
   ✦ [рекомендация 3-5]
5. Блок «красных флагов» (если применимо, иначе пропусти):
   ● КОГДА К ВРАЧУ
   ✦ [симптом/признак, при котором нужен очный визит]
6. Последняя строка: Разбор информационный, не заменяет консультацию врача

ПРАВИЛА:
- Описывай ТОЛЬКО то, что реально видно на фото. Не придумывай детали, которых нет на снимке.
- Если по фото нельзя поставить точный характер (нужен осмотр/анализ) - честно скажи об этом и направь к врачу, не домысливай диагноз.
- Выделяй «красные флаги», при которых нужен очный визит к специалисту.
- Пиши на русском, по делу, без запугивания. Без markdown-разметки и звёздочек для жирности. Между блоками - пустая строка.

` + contextText
}
