package locales

// PromptForAnalysisJSON — промпт для JSON анализа с адаптивной структурой.
func PromptForAnalysisJSON(text string) string {
	return `Ты опытный врач-диагност. Проанализируй медицинские показатели и верни ТОЛЬКО JSON.

Верни ТОЛЬКО JSON.
Без markdown.
Без комментариев.
Без текста до или после JSON.

Формат JSON:
{
  "title": "Анализ здоровья",
  "summary": "Краткое общее заключение",
  "sections": [
    {
      "type": "blood",
      "title": "Общий анализ крови",
      "indicators": [
        {
          "name": "Гемоглобин",
          "value": "145",
          "unit": "г/л",
          "normal": "120-160",
          "status": "normal",
          "score": 85
        }
      ],
      "summary": "Краткое описание по секции"
    },
    {
      "type": "lifestyle",
      "title": "Образ жизни",
      "list": ["Рекомендация 1", "Рекомендация 2"]
    },
    {
      "type": "recommendation",
      "title": "Рекомендации",
      "list": ["Совет 1", "Совет 2"]
    }
  ],
  "disclaimer": "Этот анализ носит информационный характер и не является диагнозом."
}

ТИПЫ СЕКЦИЙ (type):
- "blood" — анализы крови, биохимия, показатели лабораторных тестов
- "lifestyle" — образ жизни, сон, стресс, активность
- "nutrition" — питание, дефициты, нутриенты
- "recommendation" — общие рекомендации, советы
- "warning" — предупреждения, зоны внимания
- "profile" — общий профиль здоровья, интегральные оценки

КРИТИЧЕСКИ ВАЖНЫЕ ПРАВИЛА:
1. Генерируй JSON ТОЛЬКО с теми секциями, по которым есть данные в тексте.
2. НЕ создавай пустые секции. Если данных нет — не включай секцию.
3. Поля "indicators" заполняй только для секций типа "blood".
4. Поля "list" заполняй для секций типа "lifestyle", "recommendation", "nutrition", "warning".
5. status: строго одно из ["normal", "warning", "critical"]
6. score: целое число от 0 до 100 для каждого показателя.
7. Будь лаконичен — избегай длинных текстов.
8. Не придумывай показатели, которых нет в тексте.

Данные анализов пользователя:
` + text
}
