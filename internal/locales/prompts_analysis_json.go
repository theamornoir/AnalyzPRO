package locales

// PromptForAnalysisJSON - промпт для JSON анализа с адаптивной структурой
// (models.AdaptiveReportData). Используется для блоков дашборда «Мой профиль»
// и адаптивного HTML-отчёта.
func PromptForAnalysisJSON(text string) string {
	return `Ты опытный врач-диагност. Проанализируй приведённые медицинские показатели и верни ТОЛЬКО JSON строго по схеме ниже.

Верни ТОЛЬКО JSON.
Без markdown.
Без комментариев.
Без текста до или после JSON.

Формат JSON (строго):
{
  "title": "Анализ здоровья",
  "date": "14.03.2025",
  "summary": "Краткое общее заключение по картине в целом (2-3 предложения).",
  "sections": [
    {
      "type": "blood",
      "title": "Общий анализ крови",
      "indicators": [
        {
          "name": "Гемоглобин",
          "value": "145",
          "unit": "г/л",
          "normal": "120-160",
          "status": "normal",
          "score": 85,
          "description": "Переносит кислород по организму. От него зависит насыщение тканей кислородом."
        }
      ],
      "summary": "Краткое описание по секции: что в норме, что требует внимания."
    },
    {
      "type": "lifestyle",
      "title": "Образ жизни",
      "list": ["Рекомендация 1", "Рекомендация 2"]
    },
    {
      "type": "nutrition",
      "title": "Питание",
      "list": ["Совет 1", "Совет 2"]
    },
    {
      "type": "recommendation",
      "title": "Рекомендации",
      "list": ["Совет 1", "Совет 2"]
    },
    {
      "type": "warning",
      "title": "Зоны внимания",
      "list": ["Что требует проверки у врача"]
    },
    {
      "type": "profile",
      "title": "Профиль здоровья",
      "score": 78,
      "summary": "Интегральная оценка состояния (0-100) и пояснение."
    }
  ],
  "disclaimer": "Этот анализ носит информационный характер и не является диагнозом."
}

ТИПЫ СЕКЦИЙ (type) - строго одно из:
- "blood" - лабораторные анализы крови, биохимия, гормоны, липиды, моча и т.п. (только для них заполняй indicators).
- "lifestyle" - образ жизни, сон, стресс, активность, привычки (заполняй list).
- "nutrition" - питание, нутриенты, дефициты (заполняй list).
- "recommendation" - общие рекомендации и советы (заполняй list).
- "warning" - предупреждения и зоны внимания (заполняй list).
- "profile" - интегральный профиль здоровья с общей оценкой (заполняй score + summary).

КРИТИЧЕСКИ ВАЖНЫЕ ПРАВИЛА:
1. Генерируй JSON ТОЛЬКО с теми секциями, по которым есть данные в тексте.
2. НЕ создавай пустые секции. Если данных нет - не включай секцию.
3. У полей "indicators" заполняй значение, единицу и референс ИЗ БЛАНКА; status - строго "normal", "warning" или "critical"; score - целое 0-100 (для каждого показателя). Для каждого показателя обязательно заполняй "description" - 1-2 предложения на русском: что показывает этот показатель и что значит его отклонение от нормы (для нормы - кратко о роли показателя).
4. У секций типа "lifestyle", "nutrition", "recommendation", "warning" заполняй "list" (массив строк-советов).
5. Заполняй поле "date" датой исследования из бланка (в формате ДД.ММ.ГГГГ), если она указана; иначе оставь пустым.
5. Для "profile" укажи score (0-100) и summary с пояснением.
6. Будь лаконичен: избегай длинных текстов, пиши чётко и по делу.
7. Не придумывай показатели, которых нет в тексте, и не искажай значения.
8. Для каждого отклонения (warning/critical) давай понятное пояснение, что это значит для человека.

Данные анализов пользователя:
` + text
}
