// ============================================================================
// Демо-режим (моки) для анализов и Bioscan
// ============================================================================
// Кнопки «Демо: …» в хабе «Анализы» открывают предпросмотр готового
// результата «как заполнено» - без реальных файлов/фото и БЕЗ вызовов ИИ.
// Это чисто клиентский предпросмотр формата вывода: обычный анализ -> текст
// в чат, расширенный анализ -> HTML-документ, базовый Bioscan -> текст в чат,
// Bioscan PRO -> PDF-отчёт. Реальные данные пользователя не трогаются.
// Работает всем (и без Premium).

// handleRegularAnalysisDemo - предпросмотр обычного анализа (текстом в чат).
func (r *router) handleRegularAnalysisDemo(ctx context.Context, b *tgbot.Bot, chatID int64) bool {
	log.Printf("[DEMO] обычный анализ для chatID=%d", chatID)
	r.deleteHubBlock(ctx, b, chatID)
	r.setCurrentSection(chatID, "analysis")

	full := "ДЕМО-режим - пример результата «Обычный анализ» " +
		"(без ИИ, просто образец формата):\n\n" + demoRegularAnalysisText
	sendLongMessage(ctx, b, chatID, full, keyboards.MainMenu())
	helpers.SendSavedToSummaryDemo(ctx, b, chatID, r.webAppURL)
	return true
}

// handleExtendedAnalysisDemo - предпросмотр расширенного анализа (HTML-досье).
func (r *router) handleExtendedAnalysisDemo(ctx context.Context, b *tgbot.Bot, chatID int64) bool {
	log.Printf("[DEMO] расширенный анализ для chatID=%d", chatID)
	r.deleteHubBlock(ctx, b, chatID)
	r.setCurrentSection(chatID, "analysis")

	dossier := demoHealthDossier()
	html, err := r.reportRenderer.RenderDossier(dossier)
	if err != nil {
		log.Printf("[DEMO] ошибка рендера досье chatID=%d: %v", chatID, err)
		_, _ = b.SendMessage(ctx, &tgbot.SendMessageParams{
			ChatID:      chatID,
			Text:        locales.MsgUploadRenderError,
			ReplyMarkup: keyboards.MainMenu(),
		})
		return true
	}

	// Демо расширенного анализа - отправляем как PDF (как в реальном пути),
	// при сбое конвертации - как HTML.
	pdfBytes, convErr := r.pdfConverter.ConvertHTML(ctx, html)
	if convErr != nil {
		log.Printf("[DEMO] не удалось конвертировать досье в PDF chatID=%d: %v - отправляю HTML", chatID, convErr)
		_, _ = b.SendDocument(ctx, &tgbot.SendDocumentParams{
			ChatID: chatID,
			Document: &tgmodels.InputFileUpload{
				Filename: "Health_profile.html",
				Data:     bytes.NewReader([]byte(html)),
			},
			Caption:   locales.MsgUploadDossierCaption,
			ParseMode: "HTML",
		})
	} else {
		_, _ = b.SendDocument(ctx, &tgbot.SendDocumentParams{
			ChatID: chatID,
			Document: &tgmodels.InputFileUpload{
				Filename: "Health_profile.pdf",
				Data:     bytes.NewReader(pdfBytes),
			},
			Caption:   locales.MsgUploadDossierCaption,
			ParseMode: "HTML",
		})
	}

	r.stateManager.Reset(chatID)
	_, _ = b.SendMessage(ctx, &tgbot.SendMessageParams{
		ChatID:      chatID,
		Text:        locales.MsgAnalysisComplete,
		ReplyMarkup: keyboards.MainMenu(),
		ParseMode:   "HTML",
	})
	helpers.SendSavedToSummaryDemo(ctx, b, chatID, r.webAppURL)
	return true
}

// handleBioscanBasicDemo - предпросмотр базового (бесплатного) Bioscan (текст).
